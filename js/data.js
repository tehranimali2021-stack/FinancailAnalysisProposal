/* --- بارگذاری داده از localStorage (اگر ادمین ویرایش کرده باشد) --- */
function loadData() {
  const saved = localStorage.getItem("proposalData");
  if (saved) {
    try { return JSON.parse(saved); } catch (e) { return DEFAULT_DATA; }
  }
  return DEFAULT_DATA;
}

/* --- ذخیره داده --- */
function saveData(data) {
  localStorage.setItem("proposalData", JSON.stringify(data));
}

/* --- فرمول تعدیل تورمی --- */
function adjustInvestment(base, economy) {
  if (economy.applyInflation) {
    return Math.round(base * (1 + economy.inflationRate));
  }
  return base;
}

/* --- قالب‌بندی عدد به تومان --- */
function formatMoney(num, label) {
  return num.toLocaleString("fa-IR") + " " + label;
}
